def _get_time_context() -> dict[str, str]:
    hour = datetime.now().hour
    if 5 <= hour < 12:
        return {"period": "утро", "mood": "бодрая, позитивная"}
    elif 12 <= hour < 18:
        return {"period": "день", "mood": "рабочий режим, собранная"}
    return {"period": "вечер", "mood": "чуть теплее, но на связи"}


def _format_known_facts(known_facts: dict) -> str:
    if not known_facts:
        return "— пока ничего не известно"
    lines = []
    for field, data in known_facts.items():
        if isinstance(data, dict):
            lines.append(f"— {field}: {data.get('value', 'н/д')} ({data.get('confidence', 'н/д')})")
        else:
            lines.append(f"— {field}: {data}")
    return "\n".join(lines) if lines else "— пока ничего не известно"


